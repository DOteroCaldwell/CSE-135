const LANG_NAME = 'PHP';
const TEAM_NAME = 'Diego — UCSD Wrestling Club';

/** HTML-escape. ENT_QUOTES so the value is safe in attributes too. */
function h(?string $s): string
{
    return htmlspecialchars($s ?? '', ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function client_ip(): string
{
    return $_SERVER['REMOTE_ADDR'] ?? 'unknown';
}

function user_agent(): string
{
    return $_SERVER['HTTP_USER_AGENT'] ?? '(none sent)';
}

function server_hostname(): string
{
    return $_SERVER['SERVER_NAME'] ?? php_uname('n');
}

/** ISO-8601 with timezone, so the "generated at" value is unambiguous. */
function now_iso(): string
{
    return (new DateTimeImmutable('now'))->format(DateTimeInterface::ATOM);
}

/**
 * Read and parse the request body.
 *
 * $_POST only populates for POST + x-www-form-urlencoded, so PUT, DELETE and
 * any JSON body have to be read off php://input and parsed by hand.
 *
 * @return array{0: array<string,mixed>, 1: string} [parsed fields, raw body]
 */
function parsed_body(): array
{
    $ct  = $_SERVER['CONTENT_TYPE'] ?? '';
    $raw = file_get_contents('php://input');

    if ($raw === false) {
        $raw = '';
    }

    if (stripos($ct, 'application/json') !== false) {
        $decoded = json_decode($raw, true);
        return [is_array($decoded) ? $decoded : [], $raw];
    }

    // PHP may have already consumed the stream into $_POST.
    if ($raw === '' && !empty($_POST)) {
        return [$_POST, http_build_query($_POST)];
    }

    $fields = [];
    parse_str($raw, $fields);
    return [$fields, $raw];
}

