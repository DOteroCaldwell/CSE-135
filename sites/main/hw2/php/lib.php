/**
 * Render an associative array as a definition table.
 * Every key and value is escaped — these tables carry user-controlled data.
 *
 * @param array<string,mixed> $rows
 */
function kv_table(array $rows, string $caption): void
{
    echo "    <table class=\"kv\">\n";
    echo '      <caption>' . h($caption) . "</caption>\n";
    echo "      <tbody>\n";
    if ($rows === []) {
        echo "        <tr><td colspan=\"2\"><em>(nothing)</em></td></tr>\n";
    }
    foreach ($rows as $k => $v) {
        if (is_array($v)) {
            $v = json_encode($v, JSON_UNESCAPED_SLASHES);
        }
        echo '        <tr><th scope="row">' . h((string) $k) . '</th><td>'
            . h((string) $v) . "</td></tr>\n";
    }
    echo "      </tbody>\n    </table>\n";
}

/**
 * Emit a JSON response.
 * nosniff matters here: without it a browser can be talked into treating a
 * reflected payload in this body as HTML.
 *
 * @param array<string,mixed> $data
 */
function send_json(array $data): void
{
    header('Content-Type: application/json; charset=utf-8');
    header('X-Content-Type-Options: nosniff');
    header('Cache-Control: no-store');
    echo json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES), "\n";
}
